"""Reproducibility primitives: seeding, input pinning, and run provenance.

`AGENTS.md` states that a result which cannot be regenerated from pinned inputs is
not a result yet, and that scope and methodology commitments are enforced in code
rather than by good intentions. This module is where that enforcement lives.

Every pipeline that produces a publishable artefact should wrap its work in a
:func:`run` block:

    from amazebio.repro import run

    with run("A1.4", seed=20261013, outdir=Path("artifacts/a1-4")) as m:
        m.parameter("bitscore_threshold", 50.0)      # declared BEFORE results exist
        m.input_file(corpus_path)
        ...
        m.output_file(result_path)

On exit the block writes `run.json` next to the outputs, recording the seed, the
declared parameters, SHA-256 of every input and output, resolved tool versions,
the git commit, and the platform. That file is what makes a number in a write-up
traceable to the thing that produced it.

Two deliberate pieces of strictness:

* A run is refused on a dirty git tree unless `allow_dirty=True`. An artefact
  produced from uncommitted code cannot be regenerated by anyone else, so it is
  not publishable, and the cheapest moment to notice is before the compute.
* Parameters cannot be declared after an output has been recorded. The ordering
  constraint is the point: `AGENTS.md` requires thresholds fixed before results
  are inspected, and a manifest that permits the reverse order silently documents
  a violation as if it were compliance.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import os
import platform
import random
import subprocess
import sys
from collections.abc import Iterator
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

MANIFEST_NAME = "run.json"
_CHUNK = 1 << 20


class ReproError(RuntimeError):
    """Raised when a run would produce an artefact that cannot be regenerated."""


def sha256_file(path: str | Path) -> str:
    """SHA-256 of a file's contents, streamed so large corpora do not land in memory."""
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        while chunk := fh.read(_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def set_seeds(seed: int) -> int:
    """Seed every RNG this project might touch. Returns the seed for logging.

    `numpy` is seeded when installed but is not a dependency of this module, so the
    base environment stays small. Libraries added later that carry their own global
    RNG must be seeded here too — a seed that covers only some of the randomness is
    worse than none, because it looks like determinism.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    with contextlib.suppress(ImportError):
        import numpy as np

        np.random.seed(seed)
    return seed


def git_state(repo: Path | None = None) -> dict[str, Any]:
    """Current commit and dirtiness, or an explicit unavailable marker."""
    cwd = str(repo) if repo else None

    def _git(*args: str) -> str | None:
        try:
            out = subprocess.run(
                ["git", *args],
                cwd=cwd,
                capture_output=True,
                text=True,
                check=True,
                timeout=30,
            )
        except (subprocess.SubprocessError, OSError):
            return None
        return out.stdout.strip()

    commit = _git("rev-parse", "HEAD")
    if commit is None:
        return {"available": False}
    status = _git("status", "--porcelain")
    return {
        "available": True,
        "commit": commit,
        "branch": _git("rev-parse", "--abbrev-ref", "HEAD"),
        "dirty": bool(status),
        "dirty_paths": sorted(line[3:] for line in status.splitlines()) if status else [],
    }


def tool_version(command: list[str]) -> str | None:
    """Capture a tool's self-reported version string, or None if it cannot be run.

    Used to pin compiled dependencies in the manifest. The lockfile pins what was
    *installed*; this records what was actually *invoked*, which is the claim a
    replicator needs.
    """
    try:
        out = subprocess.run(command, capture_output=True, text=True, check=False, timeout=60)
    except (subprocess.SubprocessError, OSError):
        return None
    text = (out.stdout or out.stderr).strip()
    return text.splitlines()[0] if text else None


@dataclass
class RunManifest:
    """Provenance record for one pipeline run."""

    task: str
    seed: int | None = None
    outdir: Path | None = None
    parameters: dict[str, Any] = field(default_factory=dict)
    inputs: list[dict[str, Any]] = field(default_factory=list)
    outputs: list[dict[str, Any]] = field(default_factory=list)
    tools: dict[str, str | None] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    started_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    finished_at: str | None = None
    git: dict[str, Any] = field(default_factory=dict)

    def parameter(self, name: str, value: Any) -> None:
        """Declare a parameter or threshold.

        Refused once an output has been recorded: see this module's docstring.
        """
        if self.outputs:
            raise ReproError(
                f"parameter {name!r} declared after an output was recorded. "
                "AGENTS.md requires thresholds fixed before results are inspected; "
                "declare every parameter at the top of the run."
            )
        if name in self.parameters and self.parameters[name] != value:
            raise ReproError(
                f"parameter {name!r} redeclared with a different value "
                f"({self.parameters[name]!r} -> {value!r})"
            )
        self.parameters[name] = value

    def input_file(self, path: str | Path, *, role: str | None = None) -> Path:
        """Record and checksum a pinned input. Returns the path, so it can wrap a call."""
        p = Path(path)
        self.inputs.append(
            {"path": str(p), "sha256": sha256_file(p), "bytes": p.stat().st_size, "role": role}
        )
        return p

    def output_file(self, path: str | Path, *, role: str | None = None) -> Path:
        """Record and checksum a produced artefact."""
        p = Path(path)
        self.outputs.append(
            {"path": str(p), "sha256": sha256_file(p), "bytes": p.stat().st_size, "role": role}
        )
        return p

    def input_url(
        self,
        url: str,
        *,
        role: str | None = None,
        bytes: int | None = None,
        checksum: str | None = None,
        checksum_type: str | None = None,
        verified: bool | None = None,
    ) -> str:
        """Record a remote input that is too large to hold locally.

        A corpus can exceed the disk it is processed on — the UniRef release A1.3
        stages is 169 GB against a 30 GB working disk — so some pinned inputs are
        never files here. The pin then rests on the publisher's own verification:
        pass the published checksum and whether this run actually matched it.
        `verified=False` is the honest record of a stream that was read but not
        checked, and it is what stops such a run being cited as a verified one.
        """
        self.inputs.append(
            {
                "url": url,
                "bytes": bytes,
                "checksum": checksum,
                "checksum_type": checksum_type,
                "verified": verified,
                "role": role,
            }
        )
        return url

    def output_object(
        self,
        uri: str,
        *,
        role: str | None = None,
        bytes: int | None = None,
        sha256: str | None = None,
        **extra: Any,
    ) -> str:
        """Record an artefact that landed in object storage rather than on disk.

        Same contract as :meth:`output_file` — it counts as an output, so it
        closes the window for declaring parameters — but the checksum is supplied
        by the writer, since re-reading the object to hash it would mean pulling
        the bytes back down.
        """
        self.outputs.append({"uri": uri, "bytes": bytes, "sha256": sha256, "role": role, **extra})
        return uri

    def tool(self, name: str, command: list[str]) -> None:
        """Record the version of an external tool actually invoked by this run."""
        self.tools[name] = tool_version(command)

    def note(self, text: str) -> None:
        """Attach a free-text note — a limitation, a proxy substitution, a caveat."""
        self.notes.append(text)

    def to_dict(self) -> dict[str, Any]:
        return {
            "task": self.task,
            "seed": self.seed,
            "started_at": self.started_at,
            "finished_at": self.finished_at,
            "git": self.git,
            "parameters": self.parameters,
            "inputs": self.inputs,
            "outputs": self.outputs,
            "tools": self.tools,
            "notes": self.notes,
            "environment": {
                "python": sys.version.split()[0],
                "platform": platform.platform(),
                "machine": platform.machine(),
            },
        }

    def write(self, path: str | Path | None = None) -> Path:
        """Write the manifest as JSON. Defaults to `run.json` in the run's outdir."""
        if path is None:
            if self.outdir is None:
                raise ReproError("no outdir set, so the manifest path must be given explicitly")
            path = Path(self.outdir) / MANIFEST_NAME
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(self.to_dict(), indent=2, sort_keys=True) + "\n")
        return target


@contextlib.contextmanager
def run(
    task: str,
    *,
    seed: int | None = None,
    outdir: str | Path | None = None,
    allow_dirty: bool = False,
    repo: Path | None = None,
) -> Iterator[RunManifest]:
    """Wrap a pipeline run: seed RNGs, check the tree is clean, write provenance.

    Args:
        task: the task ID this run belongs to, e.g. ``"A1.4"``.
        seed: seed for every RNG. Pass None only for a genuinely deterministic run.
        outdir: where outputs and `run.json` land. Created if absent.
        allow_dirty: permit a run on an uncommitted tree. For local iteration only;
            never for an artefact that will be cited.
        repo: repository root for the git check. Defaults to the current directory.

    Raises:
        ReproError: if the git tree is dirty and ``allow_dirty`` is False.
    """
    manifest = RunManifest(task=task, seed=seed)
    manifest.git = git_state(repo)

    if manifest.git.get("dirty") and not allow_dirty:
        changed = ", ".join(manifest.git.get("dirty_paths", [])[:5]) or "(unknown)"
        raise ReproError(
            f"refusing to run {task} on a dirty git tree (changed: {changed}). "
            "An artefact produced from uncommitted code cannot be regenerated by "
            "anyone else. Commit first, or pass allow_dirty=True for local iteration "
            "only — never for a result that will be cited."
        )

    if seed is not None:
        set_seeds(seed)

    if outdir is not None:
        manifest.outdir = Path(outdir)
        manifest.outdir.mkdir(parents=True, exist_ok=True)

    try:
        yield manifest
    finally:
        manifest.finished_at = datetime.now(UTC).isoformat()
        if manifest.outdir is not None:
            manifest.write()
