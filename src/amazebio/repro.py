"""Reproducibility primitives: seeding, input pinning, and run provenance.

`AGENTS.md` states that a result which cannot be regenerated from pinned inputs is
not a result yet, and that scope and methodology commitments are enforced in code
rather than by good intentions. This module is where that enforcement lives.

Every pipeline that produces a publishable artefact should wrap its work in a
:func:`run` block:

    from amazebio.repro import run

    with run("A1.4", seed=20261013, outdir=Path("artifacts/a1-4")) as m:
        m.parameter("bitscore_threshold", 50.0)      # declared BEFORE results exist
        m.input_file(corpus_path)
        ...
        m.output_file(result_path)

On exit the block writes `run.json` next to the outputs, recording the seed, the
declared parameters, SHA-256 of every input and output, resolved tool versions,
the git commit, and the platform. That file is what makes a number in a write-up
traceable to the thing that produced it.

Two deliberate pieces of strictness:

* A run is refused on a dirty git tree unless `allow_dirty=True`. An artefact
  produced from uncommitted code cannot be regenerated by anyone else, so it is
  not publishable, and the cheapest moment to notice is before the compute.
* Parameters cannot be declared after an output has been recorded. The ordering
  constraint is the point: `AGENTS.md` requires thresholds fixed before results
  are inspected, and a manifest that permits the reverse order silently documents
  a violation as if it were compliance.
* **A run that produces local outputs must say where they persist.** `artifacts/`
  is git-ignored and the session container is reclaimed, so a result written only
  there is gone when the session ends. On 2026-10-19 an audit found **nine
  finished tasks with no surviving result artefact** — A2.1's deepened profile
  pass and A4.2's taxonomy benchmark among them, between them most of a day of
  compute — while every task whose tool uploaded was intact (D-188). The figures
  survived in prose, which is precisely what `AGENTS.md`'s "artefacts before
  prose" forbids relying on.

  So :func:`run` refuses to complete a run that recorded a local output and named
  no durable destination. Pass `durable="s3://bucket/prefix"` and the outputs are
  uploaded and recorded as object URIs on exit; pass `durable_exempt="<reason>"`
  for a run whose outputs genuinely need no persistence. The exemption is a
  string rather than a flag so the reason is in the manifest and greppable across
  the tree, and `tests/test_repro.py` holds the list of exempt call sites so it
  can shrink but not silently grow.

- **An upload keyed only by filename is destroyed by the next run of the same
  pipeline.** The corpus bucket has no `s3:DeleteObject`, which is what makes a
  staged corpus un-rewritable, but `PutObject` on a key that already exists
  succeeds and the previous bytes stop being readable. A3.4 published a partial
  `bins-pfam-38.2.json` and then the full one under one key, 94 minutes apart;
  nothing was lost because the replaced object was the worse of the two, which is
  luck rather than a property. So every output now goes to two keys: the stable
  one it has always had, which readers keep using, and a commit-keyed twin under
  `by-commit/<commit>/` that a later run of the same pipeline cannot reach.
  Publishing different bytes under a commit that has already published is refused
  outright, because the same code producing a different result means something
  undeclared moved. D-216.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import os
import platform
import random
import subprocess
import sys
from collections.abc import Iterator
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

MANIFEST_NAME = "run.json"

#: Where the commit-keyed copy of each durable output sits, under the run's own prefix.
#: A listing that globs the prefix for results does not see into it. D-216.
BY_COMMIT = "by-commit"
_CHUNK = 1 << 20


class ReproError(RuntimeError):
    """Raised when a run would produce an artefact that cannot be regenerated."""


def sha256_file(path: str | Path) -> str:
    """SHA-256 of a file's contents, streamed so large corpora do not land in memory."""
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        while chunk := fh.read(_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def set_seeds(seed: int) -> int:
    """Seed every RNG this project might touch. Returns the seed for logging.

    `numpy` is seeded when installed but is not a dependency of this module, so the
    base environment stays small. Libraries added later that carry their own global
    RNG must be seeded here too — a seed that covers only some of the randomness is
    worse than none, because it looks like determinism.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    with contextlib.suppress(ImportError):
        import numpy as np

        np.random.seed(seed)
    return seed


def _porcelain_path(line: str) -> str:
    """The path from one `git status --porcelain` line.

    Not a fixed `line[3:]` slice. Porcelain's status field is two columns and a space, but a
    modified-yet-unstaged file's line *begins* with a space (` M pixi.lock`) and the captured
    output is stripped as a whole — so the first such line arrives one character short and a
    fixed slice eats the first character of the path. The dirty-tree refusal then names a file
    that does not exist: "pixi.lock" reported as "ixi.lock", "tests/..." as "ests/...", both
    observed. The existing test missed it because an *untracked* file's line (`?? new.txt`) has
    no leading space, which is the one case a fixed slice gets right.
    """
    body = line.lstrip()
    _, _, path = body.partition(" ")
    return (path or body).strip().strip('"')


def git_state(repo: Path | None = None) -> dict[str, Any]:
    """Current commit and dirtiness, or an explicit unavailable marker."""
    cwd = str(repo) if repo else None

    def _git(*args: str) -> str | None:
        try:
            out = subprocess.run(
                ["git", *args],
                cwd=cwd,
                capture_output=True,
                text=True,
                check=True,
                timeout=30,
            )
        except (subprocess.SubprocessError, OSError):
            return None
        return out.stdout.strip()

    commit = _git("rev-parse", "HEAD")
    if commit is None:
        return {"available": False}
    status = _git("status", "--porcelain")
    return {
        "available": True,
        "commit": commit,
        "branch": _git("rev-parse", "--abbrev-ref", "HEAD"),
        "dirty": bool(status),
        "dirty_paths": sorted(_porcelain_path(line) for line in status.splitlines())
        if status
        else [],
    }


def tool_version(command: list[str]) -> str | None:
    """Capture a tool's self-reported version string, or None if it cannot be run.

    Used to pin compiled dependencies in the manifest. The lockfile pins what was
    *installed*; this records what was actually *invoked*, which is the claim a
    replicator needs.
    """
    try:
        out = subprocess.run(command, capture_output=True, text=True, check=False, timeout=60)
    except (subprocess.SubprocessError, OSError):
        return None
    text = (out.stdout or out.stderr).strip()
    return text.splitlines()[0] if text else None


@dataclass
class RunManifest:
    """Provenance record for one pipeline run."""

    task: str
    seed: int | None = None
    outdir: Path | None = None
    parameters: dict[str, Any] = field(default_factory=dict)
    inputs: list[dict[str, Any]] = field(default_factory=list)
    outputs: list[dict[str, Any]] = field(default_factory=list)
    tools: dict[str, str | None] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    started_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    finished_at: str | None = None
    git: dict[str, Any] = field(default_factory=dict)
    #: Where the local outputs were copied to, or why they were not. One of the two is
    #: always set for a run that produced local outputs — :func:`run` refuses otherwise.
    durable: str | None = None
    durable_exempt: str | None = None
    #: `local path -> object URI` for each output copied to durable storage.
    uploaded: dict[str, str] = field(default_factory=dict)
    #: `local path -> object URI` for the commit-keyed copy of each output. The stable key
    #: in `uploaded` is replaced by a later run of the same pipeline; this one is not.
    by_commit: dict[str, str] = field(default_factory=dict)
    #: Why this run may replace bytes its own commit already published. D-216.
    replace_durable: str | None = None
    #: Why the upload did not happen although `durable` was set. Present only under test.
    upload_skipped: str | None = None

    def parameter(self, name: str, value: Any) -> None:
        """Declare a parameter or threshold.

        Refused once an output has been recorded: see this module's docstring.
        """
        if self.outputs:
            raise ReproError(
                f"parameter {name!r} declared after an output was recorded. "
                "AGENTS.md requires thresholds fixed before results are inspected; "
                "declare every parameter at the top of the run."
            )
        if name in self.parameters and self.parameters[name] != value:
            raise ReproError(
                f"parameter {name!r} redeclared with a different value "
                f"({self.parameters[name]!r} -> {value!r})"
            )
        self.parameters[name] = value

    def input_file(self, path: str | Path, *, role: str | None = None) -> Path:
        """Record and checksum a pinned input. Returns the path, so it can wrap a call."""
        p = Path(path)
        self.inputs.append(
            {"path": str(p), "sha256": sha256_file(p), "bytes": p.stat().st_size, "role": role}
        )
        return p

    def output_file(self, path: str | Path, *, role: str | None = None) -> Path:
        """Record and checksum a produced artefact."""
        p = Path(path)
        self.outputs.append(
            {"path": str(p), "sha256": sha256_file(p), "bytes": p.stat().st_size, "role": role}
        )
        return p

    def input_url(
        self,
        url: str,
        *,
        role: str | None = None,
        bytes: int | None = None,
        checksum: str | None = None,
        checksum_type: str | None = None,
        verified: bool | None = None,
    ) -> str:
        """Record a remote input that is too large to hold locally.

        A corpus can exceed the disk it is processed on — the UniRef release A1.3
        stages is 169 GB against a 30 GB working disk — so some pinned inputs are
        never files here. The pin then rests on the publisher's own verification:
        pass the published checksum and whether this run actually matched it.
        `verified=False` is the honest record of a stream that was read but not
        checked, and it is what stops such a run being cited as a verified one.
        """
        self.inputs.append(
            {
                "url": url,
                "bytes": bytes,
                "checksum": checksum,
                "checksum_type": checksum_type,
                "verified": verified,
                "role": role,
            }
        )
        return url

    def output_object(
        self,
        uri: str,
        *,
        role: str | None = None,
        bytes: int | None = None,
        sha256: str | None = None,
        **extra: Any,
    ) -> str:
        """Record an artefact that landed in object storage rather than on disk.

        Same contract as :meth:`output_file` — it counts as an output, so it
        closes the window for declaring parameters — but the checksum is supplied
        by the writer, since re-reading the object to hash it would mean pulling
        the bytes back down.
        """
        self.outputs.append({"uri": uri, "bytes": bytes, "sha256": sha256, "role": role, **extra})
        return uri

    def tool(self, name: str, command: list[str]) -> None:
        """Record the version of an external tool actually invoked by this run."""
        self.tools[name] = tool_version(command)

    def note(self, text: str) -> None:
        """Attach a free-text note — a limitation, a proxy substitution, a caveat."""
        self.notes.append(text)

    def to_dict(self) -> dict[str, Any]:
        return {
            "task": self.task,
            "seed": self.seed,
            "started_at": self.started_at,
            "finished_at": self.finished_at,
            "git": self.git,
            "parameters": self.parameters,
            "inputs": self.inputs,
            "outputs": self.outputs,
            "tools": self.tools,
            "notes": self.notes,
            "durable": self.durable,
            "durable_exempt": self.durable_exempt,
            "uploaded": self.uploaded,
            "by_commit": self.by_commit,
            "replace_durable": self.replace_durable,
            "upload_skipped": self.upload_skipped,
            "environment": {
                "python": sys.version.split()[0],
                "platform": platform.platform(),
                "machine": platform.machine(),
            },
        }

    def write(self, path: str | Path | None = None) -> Path:
        """Write the manifest as JSON. Defaults to `run.json` in the run's outdir."""
        if path is None:
            if self.outdir is None:
                raise ReproError("no outdir set, so the manifest path must be given explicitly")
            path = Path(self.outdir) / MANIFEST_NAME
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(self.to_dict(), indent=2, sort_keys=True) + "\n")
        return target


def _split_s3(uri: str) -> tuple[str, str]:
    if not uri.startswith("s3://"):
        raise ReproError(f"durable destination must be an s3:// URI, got {uri!r}")
    bucket, _, prefix = uri[len("s3://") :].partition("/")
    if not bucket:
        raise ReproError(f"durable destination names no bucket: {uri!r}")
    return bucket, prefix.strip("/")


def in_test_run() -> bool:
    """Whether this process is executing under pytest.

    Load-bearing, and it was paid for. Several tests drive a tool's `main()` end-to-end with no
    client injected — that is the point of them, since an on-instance path is the one thing a
    dry run cannot check. Giving those tools `durable=` therefore made them upload their
    *synthetic fixtures* to the corpus bucket, which has no `s3:DeleteObject`: the junk is
    permanent, and four real A1.6 objects were overwritten before this existed.

    So an upload is never attempted from a test unless the test supplied the client itself.
    """
    return bool(os.environ.get("PYTEST_CURRENT_TEST") or os.environ.get("AMAZEBIO_NO_UPLOAD"))


def _client(uploader: Any) -> Any:
    if uploader is not None:
        return uploader
    from amazebio import objectstore

    return objectstore.client()


def commit_of(manifest: RunManifest) -> str | None:
    """The commit this run's code came from, wherever it was recorded.

    In this container `repro` reads it from the checkout. On an EC2 instance there is no
    checkout, so the launcher passes it in and the tool declares it as a `code_commit`
    parameter; both are the same fact and either will key an object.
    """
    commit = manifest.git.get("commit") if manifest.git else None
    return commit or manifest.parameters.get("code_commit") or None


def _relative_key(manifest: RunManifest, path: Path) -> str:
    root = Path(manifest.outdir) if manifest.outdir else path.parent
    try:
        rel = path.relative_to(root)
    except ValueError:
        rel = Path(path.name)
    return rel.as_posix()


def durable_keys(manifest: RunManifest, durable: str, path: Path) -> tuple[str, str, str | None]:
    """`(bucket, stable key, commit-keyed key)` for one output.

    The stable key is what it has always been — the output's path under the run's prefix —
    so everything that reads a result by name keeps finding it. The commit-keyed copy sits
    beside it under `by-commit/<commit>/`, out of the way of a listing that globs the
    prefix, and is the one that cannot be replaced by a later run of the same pipeline.

    Two keys rather than one because the bucket has no `s3:DeleteObject` but `PutObject`
    on an existing key succeeds regardless: un-rewritable is a property of deletion here,
    not of the key. D-216.
    """
    bucket, prefix = _split_s3(durable)
    rel = _relative_key(manifest, path)
    stable = f"{prefix}/{rel}" if prefix else rel
    commit = commit_of(manifest)
    if commit is None:
        return bucket, stable, None
    by_commit = f"{prefix}/{BY_COMMIT}/{commit}/{rel}" if prefix else f"{BY_COMMIT}/{commit}/{rel}"
    return bucket, stable, by_commit


def _head(client: Any, bucket: str, key: str) -> dict[str, Any] | None:
    """The object's metadata, or `None` if it is not there. Any other failure is raised."""
    try:
        return client.head_object(Bucket=bucket, Key=key)
    except Exception as exc:  # botocore raises ClientError; this module does not import it
        code = str(getattr(exc, "response", {}).get("Error", {}).get("Code", ""))
        status = getattr(exc, "response", {}).get("ResponseMetadata", {}).get("HTTPStatusCode")
        if code in {"404", "NoSuchKey", "NotFound"} or status == 404:
            return None
        raise


def _check_commit_keys(manifest: RunManifest, durable: str, client: Any) -> None:
    """Refuse before uploading anything if this commit already published other bytes.

    A re-run at the same commit producing the same bytes is a no-op and passes. One
    producing *different* bytes means something undeclared moved — an input, the
    environment, a parameter the tool reads but does not record — and writing it would
    destroy the copy the earlier run's `run.json` points at. The run is finished by the
    time this fires, so the outputs are still on disk; what it stops is the overwrite.
    """
    if manifest.replace_durable:
        return
    clashes: list[str] = []
    for entry in manifest.outputs:
        local = entry.get("path")
        if not local or not Path(local).exists():
            continue
        bucket, _, by_commit = durable_keys(manifest, durable, Path(local))
        if by_commit is None:
            continue
        head = _head(client, bucket, by_commit)
        if head is None:
            continue
        published = str(head.get("Metadata", {}).get("sha256", ""))
        if published and published != entry.get("sha256"):
            clashes.append(
                f"  s3://{bucket}/{by_commit}\n"
                f"    published {published}\n"
                f"    now       {entry.get('sha256')}"
            )
    if clashes:
        raise ReproError(
            f"{manifest.task}: this commit has already published different bytes for "
            + f"{len(clashes)} output(s), and the bucket cannot delete what it replaces:\n"
            + "\n".join(clashes)
            + "\nSame code and different results means an input or a parameter moved "
            "without being declared. Find what moved; if the replacement is intended, "
            "pass replace_durable='<reason>' and it lands in the manifest."
        )


def _upload_one(manifest: RunManifest, durable: str, path: Path, client: Any = None) -> str:
    """Copy one local file to its stable key and to its commit-keyed twin.

    Returns the stable URI, which is what `run.json` has always recorded; the commit-keyed
    URI is recorded alongside it so a reader can reach the copy no later run can replace.
    """
    bucket, stable, by_commit = durable_keys(manifest, durable, path)
    body = path.read_bytes()
    metadata = {"sha256": hashlib.sha256(body).hexdigest()}
    commit = commit_of(manifest)
    if commit:
        metadata["commit"] = commit
    handle = client or _client(None)
    handle.put_object(Bucket=bucket, Key=stable, Body=body, Metadata=metadata)
    uri = f"s3://{bucket}/{stable}"
    if by_commit is not None:
        handle.put_object(Bucket=bucket, Key=by_commit, Body=body, Metadata=metadata)
        manifest.by_commit[str(path)] = f"s3://{bucket}/{by_commit}"
    manifest.uploaded[str(path)] = uri
    return uri


def _upload_outputs(manifest: RunManifest, durable: str, client: Any) -> dict[str, str]:
    """Copy every local output under the durable prefix, recording each as an object URI.

    Recorded with :meth:`RunManifest.output_object` as well as on disk, so a reader of
    `run.json` can find the durable copy without knowing this function's key scheme.
    """
    _check_commit_keys(manifest, durable, client)
    uploaded: dict[str, str] = {}
    for entry in list(manifest.outputs):
        local = entry.get("path")
        if not local:
            continue
        path = Path(local)
        if not path.exists():
            continue
        uri = _upload_one(manifest, durable, path, client)
        uploaded[str(path)] = uri
        entry["durable_uri"] = uri
        if str(path) in manifest.by_commit:
            entry["by_commit_uri"] = manifest.by_commit[str(path)]
    return uploaded


@contextlib.contextmanager
def run(
    task: str,
    *,
    seed: int | None = None,
    outdir: str | Path | None = None,
    allow_dirty: bool = False,
    repo: Path | None = None,
    manifest_name: str = MANIFEST_NAME,
    durable: str | None = None,
    durable_exempt: str | None = None,
    replace_durable: str | None = None,
    uploader: Any = None,
) -> Iterator[RunManifest]:
    """Wrap a pipeline run: seed RNGs, check the tree is clean, write provenance.

    Args:
        task: the task ID this run belongs to, e.g. ``"A1.4"``.
        seed: seed for every RNG. Pass None only for a genuinely deterministic run.
        outdir: where outputs and `run.json` land. Created if absent.
        allow_dirty: permit a run on an uncommitted tree. For local iteration only;
            never for an artefact that will be cited.
        repo: repository root for the git check. Defaults to the current directory.
        manifest_name: filename for the manifest inside `outdir`. Pass a distinct name
            where more than one pipeline writes to the same directory — otherwise the
            second run silently overwrites the first one's provenance, which A1.5 hit
            with two staging passes running at once.
        durable: `s3://bucket/prefix` the local outputs are copied to on a clean exit.
            Required for any run that records a local output, unless `durable_exempt`
            is given. See this module's docstring for what it cost not to have this.
        durable_exempt: why this run's outputs need no durable copy. Mutually exclusive
            with `durable`. A reason, not a flag — it lands in the manifest.
        replace_durable: why this run may publish bytes different from the ones its own
            commit already published. Without it such a run is refused, because the
            bucket has no delete and the replaced copy is what an earlier `run.json`
            points at. A reason, not a flag — it lands in the manifest. D-216.
        uploader: object-store client. Defaults to `amazebio.objectstore.client()`,
            imported lazily so a run with no `durable` needs no boto3.

    Raises:
        ReproError: if the git tree is dirty and ``allow_dirty`` is False; if both
            `durable` and `durable_exempt` are given; or if the run recorded a local
            output and named neither.
    """
    if durable and durable_exempt:
        raise ReproError(
            f"{task}: pass either durable= or durable_exempt=, not both. If the outputs "
            "persist, say where; if they need not, say why."
        )
    if durable:
        # Checked here, not at exit: a destination that cannot be parsed should fail before the
        # compute rather than after it, which is the same reason the dirty-tree check is early.
        _split_s3(durable)
    manifest = RunManifest(task=task, seed=seed)
    manifest.git = git_state(repo)

    if manifest.git.get("dirty") and not allow_dirty:
        changed = ", ".join(manifest.git.get("dirty_paths", [])[:5]) or "(unknown)"
        raise ReproError(
            f"refusing to run {task} on a dirty git tree (changed: {changed}). "
            "An artefact produced from uncommitted code cannot be regenerated by "
            "anyone else. Commit first, or pass allow_dirty=True for local iteration "
            "only — never for a result that will be cited."
        )

    if seed is not None:
        set_seeds(seed)

    if outdir is not None:
        manifest.outdir = Path(outdir)
        manifest.outdir.mkdir(parents=True, exist_ok=True)

    manifest.durable = durable
    manifest.durable_exempt = durable_exempt
    manifest.replace_durable = replace_durable

    failed = False
    try:
        yield manifest
    except BaseException:
        failed = True
        raise
    finally:
        manifest.finished_at = datetime.now(UTC).isoformat()
        local = [o for o in manifest.outputs if o.get("path")]
        # Upload before writing run.json so the manifest records the keys, then upload
        # run.json itself: a durable copy of the outputs with no provenance beside it is
        # not citable, which is the whole point of persisting them.
        persisting = bool(durable) and bool(local) and not failed
        if persisting and uploader is None and in_test_run():
            # Skipped rather than refused: these tests are meant to run the tool, just not to
            # write to the real bucket. Recorded so a manifest produced under test cannot be
            # mistaken for one whose outputs were actually persisted.
            manifest.upload_skipped = "test run: no uploader injected"
            persisting = False
        client = _client(uploader) if persisting else None
        if persisting:
            manifest.uploaded = _upload_outputs(manifest, durable, client)
        if manifest.outdir is not None:
            written = manifest.write(Path(manifest.outdir) / manifest_name)
            if persisting:
                _upload_one(manifest, durable, written, client)
        # Checked last, and skipped when the body raised: a run that failed has no
        # result to persist, and masking its exception with this one would hide the
        # real failure.
        if not failed and local and not durable and not durable_exempt:
            raise ReproError(
                f"{task} recorded {len(local)} local output(s) under "
                f"{manifest.outdir} and named no durable destination. `artifacts/` is "
                "git-ignored and this container is reclaimed, so these files will not "
                "survive the session — nine finished tasks lost their results exactly "
                "this way (D-188). Pass durable='s3://bucket/prefix' to persist them, "
                "or durable_exempt='<reason>' if they genuinely need no copy."
            )
